// Generate src/generated/assets.ts: every third-party asset the renderer
// inlines into a deck, as plain exported strings.
//
//   - reveal.js core CSS/JS, the white + black base themes, and the
//     notes/search/zoom plugins (read verbatim from the reveal.js package);
//   - KaTeX JS + CSS, with every woff2 font embedded as a data URI and the
//     woff/ttf fallbacks stripped (the deck renders in a null-origin
//     sandboxed iframe where relative font URLs don't resolve);
//   - reveal.js's print/pdf.scss compiled to CSS (reveal ships it only as
//     SCSS; it is standalone, so a one-off compile is enough).
//
// This replaces the `?raw` imports and the `virtual:katex-inlined` /
// `virtual:reveal-print-css` Vite plugins, so the renderer no longer needs a
// bundler to resolve its assets and can run anywhere plain TS/JS runs.
//
// The output is git-ignored and regenerated by the predev / prebuild /
// pretest / pretypecheck npm hooks. Run it from the package directory.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as sass from "sass";

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(HERE, "..");
const OUT = resolve(PKG_ROOT, "src/generated/assets.ts");

// Resolve packages the way Node would from this package, so the script keeps
// working if npm hoists them differently.
const require = createRequire(resolve(PKG_ROOT, "package.json"));
const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`));
const revealDir = pkgDir("reveal.js");
const katexDist = resolve(pkgDir("katex"), "dist");
const version = (dir) => JSON.parse(readFileSync(resolve(dir, "package.json"), "utf8")).version;

const read = (dir, rel) => readFileSync(resolve(dir, rel), "utf8");

// --- KaTeX, fonts inlined ---------------------------------------------------
const fontsDir = resolve(katexDist, "fonts");
const fontMap = new Map();
for (const file of readdirSync(fontsDir)) {
  if (!file.endsWith(".woff2")) continue;
  fontMap.set(file, readFileSync(resolve(fontsDir, file)).toString("base64"));
}
let katexCss = read(katexDist, "katex.min.css");
katexCss = katexCss.replace(/url\(fonts\/(KaTeX_[^)]+\.woff2)\)/g, (match, file) => {
  const b64 = fontMap.get(file);
  return b64 ? `url(data:font/woff2;base64,${b64})` : match;
});
// Strip ,url(fonts/...) format("woff") and format("truetype") fallbacks.
katexCss = katexCss.replace(/,url\(fonts\/[^)]+\.(woff|ttf)\)\s*format\("[^"]+"\)/g, "");

// --- reveal.js print stylesheet ---------------------------------------------
const revealPrintCss = sass.compile(resolve(revealDir, "css/print/pdf.scss"), { style: "expanded" }).css;

const assets = {
  revealResetCss: read(revealDir, "dist/reset.css"),
  revealCss: read(revealDir, "dist/reveal.css"),
  revealJs: read(revealDir, "dist/reveal.js"),
  revealThemeWhiteCss: read(revealDir, "dist/theme/white.css"),
  revealThemeBlackCss: read(revealDir, "dist/theme/black.css"),
  revealNotesJs: read(revealDir, "plugin/notes/notes.js"),
  revealSearchJs: read(revealDir, "plugin/search/search.js"),
  revealZoomJs: read(revealDir, "plugin/zoom/zoom.js"),
  revealPrintCss,
  katexJs: read(katexDist, "katex.min.js"),
  katexCss,
};

const revealVersion = version(revealDir);
const katexVersion = version(resolve(katexDist, ".."));

let out = `// GENERATED by scripts/gen-assets.mjs — do not edit, do not commit.\n`;
out += `// reveal.js ${revealVersion}, KaTeX ${katexVersion}\n\n`;
out += `export const revealVersion = ${JSON.stringify(revealVersion)};\n`;
out += `export const katexVersion = ${JSON.stringify(katexVersion)};\n`;
for (const [name, value] of Object.entries(assets)) {
  out += `export const ${name}: string = ${JSON.stringify(value)};\n`;
}

mkdirSync(dirname(OUT), { recursive: true });
// Skip the write when nothing changed so file watchers (vite dev, vitest
// watch) don't see a spurious modification on every run.
let previous = null;
try { previous = readFileSync(OUT, "utf8"); } catch { /* first run */ }
if (previous !== out) writeFileSync(OUT, out);
console.log(`gen-assets: ${OUT.slice(PKG_ROOT.length + 1)} (${(out.length / 1024).toFixed(0)} kB, reveal.js ${revealVersion}, KaTeX ${katexVersion})${previous === out ? " — unchanged" : ""}`);
